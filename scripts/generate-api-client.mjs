import { execFile } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(scriptDirectory, '..');
const documentPath = resolve(repositoryRoot, 'apps/api/openapi.json');
const outputDirectory = resolve(repositoryRoot, 'packages/api-client/src');
const runFile = promisify(execFile);

const document = JSON.parse(await readFile(documentPath, 'utf8'));
const schemas = document.components?.schemas ?? {};

const refName = (ref) => ref.slice(ref.lastIndexOf('/') + 1);

const renderType = (schema) => {
    if (!schema) return 'unknown';
    if (schema.$ref) return `components['schemas']['${refName(schema.$ref)}']`;
    if (schema.enum)
        return schema.enum.map((value) => JSON.stringify(value)).join(' | ');
    if (schema.const !== undefined) return JSON.stringify(schema.const);
    if (schema.anyOf || schema.oneOf) {
        return (schema.anyOf ?? schema.oneOf).map(renderType).join(' | ');
    }
    if (schema.type === 'array') return `Array<${renderType(schema.items)}>`;
    if (
        schema.type === 'object' ||
        schema.properties ||
        schema.additionalProperties
    ) {
        const properties = Object.entries(schema.properties ?? {}).map(
            ([name, value]) => {
                const optional = (schema.required ?? []).includes(name)
                    ? ''
                    : '?';
                return `        ${JSON.stringify(name)}${optional}: ${renderType(value)};`;
            },
        );
        if (schema.additionalProperties) {
            properties.push(
                `        [key: string]: ${renderType(schema.additionalProperties)};`,
            );
        }
        return properties.length > 0
            ? `\n{\n${properties.join('\n')}\n    }`
            : 'Record<string, never>';
    }
    if (schema.type === 'integer' || schema.type === 'number') return 'number';
    if (schema.type === 'boolean') return 'boolean';
    if (schema.type === 'string') return 'string';
    return 'unknown';
};

const renderContent = (content) => {
    const entries = Object.entries(content ?? {}).map(
        ([mediaType, value]) =>
            `            ${JSON.stringify(mediaType)}: ${renderType(value.schema)};`,
    );
    return entries.length > 0
        ? `{\n${entries.join('\n')}\n        }`
        : 'Record<string, never>';
};

const renderRequest = (operation) => {
    const request = {};
    if (operation.parameters) {
        for (const parameter of operation.parameters) {
            const key = parameter.in;
            request[key] ??= {};
            request[key][parameter.name] = {
                optional: !parameter.required,
                type: renderType(parameter.schema),
            };
        }
    }
    if (operation.requestBody) {
        request.body = { content: operation.requestBody.content };
    }
    const entries = Object.entries(request).map(([location, values]) => {
        if (location === 'body') {
            return `        requestBody: {\n            content: ${renderContent(values.content)};\n        };`;
        }
        const fields = Object.entries(values).map(
            ([name, value]) =>
                `                ${JSON.stringify(name)}${value.optional ? '?' : ''}: ${value.type};`,
        );
        return `        ${location}: {\n${fields.join('\n')}\n        };`;
    });
    return entries.length > 0 ? `\n${entries.join('\n')}` : '';
};

const renderResponses = (operation) => {
    const entries = Object.entries(operation.responses ?? {}).map(
        ([status, response]) => {
            const content = renderContent(response.content);
            return `            ${JSON.stringify(status)}: {\n                content: ${content};\n            };`;
        },
    );
    return entries.join('\n');
};

const renderPaths = () =>
    Object.entries(document.paths ?? {})
        .map(([path, pathItem]) => {
            const operations = Object.entries(pathItem)
                .filter(([method]) =>
                    ['get', 'post', 'patch', 'put', 'delete'].includes(method),
                )
                .map(
                    ([method, operation]) =>
                        `        ${method}: {${renderRequest(operation)}\n        responses: {\n${renderResponses(operation)}\n        };\n    };`,
                )
                .join('\n');
            return `    ${JSON.stringify(path)}: {\n${operations}\n    };`;
        })
        .join('\n');

const schemaSource = `// This file is generated by scripts/generate-api-client.mjs. Do not edit it directly.
export interface components {
    schemas: {
${Object.entries(schemas)
    .map(
        ([name, schema]) =>
            `        ${JSON.stringify(name)}: ${renderType(schema)};`,
    )
    .join('\n')}
    };
}

export interface paths {
${renderPaths()}
}
`;

const clientSource = `// This file is generated by scripts/generate-api-client.mjs. Do not edit it directly.
export interface ApiClientOptions {
    baseUrl?: string;
    token?: string;
    fetchImplementation?: typeof globalThis.fetch;
}

export interface ApiClient {
    request(path: string, init?: RequestInit): Promise<Response>;
}

export const createApiClient = ({
    baseUrl = '',
    token,
    fetchImplementation = globalThis.fetch,
}: ApiClientOptions = {}): ApiClient => ({
    request: (path, init = {}) => {
        const headers = new Headers(init.headers);
        headers.set('accept', 'application/json');
        if (token) headers.set('authorization', \`Bearer \${token}\`);
        return fetchImplementation(\`\${baseUrl}\${path}\`, { ...init, headers });
    },
});
`;

await writeFile(resolve(outputDirectory, 'schema.ts'), schemaSource);
await writeFile(resolve(outputDirectory, 'client.ts'), clientSource);
await runFile(resolve(repositoryRoot, 'node_modules/.bin/biome'), [
    'format',
    '--write',
    resolve(outputDirectory, 'schema.ts'),
    resolve(outputDirectory, 'client.ts'),
]);
// biome-ignore lint/suspicious/noConsole: report generated artifact paths
console.log('Generated packages/api-client/src/schema.ts and client.ts');
